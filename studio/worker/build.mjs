// Builds a single-file Worker module (dist/worker.js) for API/dashboard deploys:
// requests.js + index.js, with the studio files inlined (no assets binding needed).
// Usage: node studio/worker/build.mjs <outdir>
import fs from "node:fs"; import path from "node:path"; import url from "node:url";
const here = path.dirname(url.fileURLToPath(import.meta.url)), studio = path.join(here, "..");
const files = ["index.html", "studio.js", "requests.js", "grok.js", "media.js", "cloud.js", "assemble.js", "manifest.webmanifest"];
const content = Object.fromEntries(files.map(f => ["/" + f, fs.readFileSync(path.join(studio, f), "utf8")]));
const worker = fs.readFileSync(path.join(here, "index.js"), "utf8").replace('import "../requests.js";\n', "");
const out = "// generated by studio/worker/build.mjs – do not edit\n" +
  fs.readFileSync(path.join(studio, "requests.js"), "utf8") + "\n" +
  "globalThis.__STUDIO_CONTENT = " + JSON.stringify(content) + ";\n" + worker;
const dir = process.argv[2] || path.join(here, "dist");
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, "worker.js"), out);
console.log("built", path.join(dir, "worker.js"), out.length, "bytes");
