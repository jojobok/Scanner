def theme_prompt(p: Parasha, style: Style) -> str:
    return f"""פרשת השבוע: {p.title_he} ({p.name_en}), שבת {p.shabbat_date.isoformat()}.

משימה: מצא את הנושא המרכזי של הפרשה שיעבוד הכי טוב כסרטון קצר (עד {int(style.max_seconds)} שניות).
1. הצע 3 נושאים מרכזיים אפשריים. לכל אחד: כותרת, הסבר של משפט-שניים, פסוק עוגן מדויק, והמסר לחיים של היום.
2. בחר את החזק ביותר לסרטון - זה שיש לו גם סיפור ויזואלי מהפרשה וגם מסר אישי שנוגע ללב.

קהל יעד: {style.audience}

החזר JSON במבנה הזה בדיוק:
{{
  "candidates": [
    {{"title": "...", "summary": "...", "anchor_verse": "טקסט הפסוק (ספר פרק:פסוק)", "life_message": "..."}}
  ],
  "chosen_index": 0,
  "why_chosen": "..."
}}"""


def script_prompt(p: Parasha, theme: dict, style: Style) -> str:
    words = int(style.target_seconds * 2.1)  # קצב קריינות רגוע ~2.1 מילים לשנייה
    return f"""פרשת השבוע: {p.title_he}.
הנושא שנבחר: {theme.get("title")}
תקציר: {theme.get("summary")}
פסוק עוגן: {theme.get("anchor_verse")}
מסר: {theme.get("life_message")}

כתוב תסריט לסרטון אנכי קולנועי, בנוי כרצף תמונות עם מעברי דעיכה רכים וקריינות ברקע (בלי טקסט על המסך).
- אורך הקריינות הכולל: כ-{words} מילים (≈{int(style.target_seconds)} שניות). בשום מקרה לא יותר מ-{int(style.max_seconds)} שניות.
- {style.scenes_min} עד {style.scenes_max} סצנות. כל סצנה = תמונה אחת שמוצגת כ-4-6 שניות + משפט קריינות קצר אחד (8-12 מילים).
- הסיפור מסופר לפי סדר האירועים בפרשה, כמו טריילר. טון: {style.tone}
- סצנה 1: תמונת פתיחה חזקה + משפט שתופס.
- סצנה אחרונה: תמונה סמלית ושקטה (למשל נר דולק, אוהל באור), עם המסר לשבת ו"{style.outro_text}".
- קודם הגדר "characters": כל דמות שחוזרת בסרטון, עם תיאור מראה קבוע באנגלית
  (גיל, פנים, זקן/שיער, צבעי בגדים מדויקים, כיסוי ראש). דוגמה: Rebecca - young woman, olive skin,
  dark eyes, saffron-yellow headscarf, long rust-red dress.
- לכל סצנה image_prompt באנגלית שעומד בפני עצמו: מעתיקים לתוכו את התיאור המלא של כל דמות שמופיעה,
  ומוסיפים פעולה, מקום, זווית מצלמה ותאורה. סגנון אחיד לכל התמונות: {style.visual_style}
  כללים מחייבים: {style.image_rules}
- on_screen_text: עד 5 מילים בעברית (ישמש רק אם יופעלו כותרות על המסך).

החזר JSON במבנה הזה בדיוק:
{{
  "title": "כותרת הסרטון (עד 8 מילים)",
  "hook": "משפט הפתיחה",
  "characters": [{{"name": "...", "look": "..."}}],
  "scenes": [
    {{"narration": "...", "on_screen_text": "...", "image_prompt": "..."}}
  ],
  "caption": "טקסט לפוסט ברשתות (2-4 שורות)",
  "hashtags": ["#פרשת_השבוע", "..."],
  "sources": ["מקורות שעליהם התסריט מבוסס, למשל: בראשית כד:יב, רש\"י שם"]
}}"""
